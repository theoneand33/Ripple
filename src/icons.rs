/// The icon for a WMO weather code; the sun while there is none.
pub fn weather(code: Option<u64>) -> &'static Icon {
    match code {
        Some(1 | 2) => &CLOUD_SUN,
        Some(3 | 45 | 48) => &CLOUD,
        Some(51..=57 | 61..=67 | 80..=82) => &CLOUD_RAIN,
        Some(71..=77 | 85 | 86) => &CLOUD_SNOW,
        Some(95..=99) => &CLOUD_LIGHTNING,
        _ => &SUN,
    }
}

